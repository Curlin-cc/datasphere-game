"""Chapter 3 (Data integration): connections, on-premise + certificate, remote tables, replication flows, CRM projection, failed load."""
import sys
from playwright.sync_api import sync_playwright
from common import Game, save_before, SPACES

S = sys.argv[1] if len(sys.argv) > 1 else '.'
TENANT = {"spaces": SPACES, "shares": [], "activeSpace": "RHN_IN"}

with sync_playwright() as p:
    g = Game(p, S)
    pg = g.pg
    g.start(save_before(3, 'c03-m01', TENANT))
    g.walk_tutorial()

    def conn_create(type_id, host, business, tech, onprem=None, location=None, tls=None, auth=None):
        pg.click('#conn-create'); pg.click(f'[data-type="{type_id}"]')
        pg.fill('[name="host"]', host)
        if onprem is not None: pg.check(f'[name="deploy"][value="{"onprem" if onprem else "cloud"}"]')
        if location is not None: pg.fill('[name="location"]', location)
        if tls is not None:
            (pg.check if tls else pg.uncheck)('[name="tls"]')
        if auth is not None: pg.select_option('[name="auth"]', auth)
        pg.fill('[name="business"]', business); pg.fill('[name="technical"]', tech)
        pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(250)
        e = pg.locator('.form-error')
        if e.count() and e.inner_text().strip():
            print('   FORM ERROR:', e.inner_text()); pg.click('[data-act="cancel"]')

    def select_conn(name):
        pg.check(f'[name="conn-sel"][value="{name}"]'); pg.wait_for_timeout(150)

    def validate(name):
        select_conn(name); pg.click('#conn-validate'); pg.wait_for_selector('.dialog')
        print('   VALIDATE', name, ':', pg.inner_text('.dialog .guide-lead'))
        pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(150)

    def edit_conn(name, **kw):
        select_conn(name); pg.click('#conn-edit')
        if 'onprem' in kw: pg.check(f'[name="deploy"][value="{"onprem" if kw["onprem"] else "cloud"}"]')
        if 'location' in kw: pg.fill('[name="location"]', kw['location'])
        if 'tls' in kw: (pg.check if kw['tls'] else pg.uncheck)('[name="tls"]')
        if 'auth' in kw: pg.select_option('[name="auth"]', kw['auth'])
        pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)

    # ---------------- m01: wrong space and auth first
    g.nav('connections')
    pg.select_option('#conn-space', 'RHN_HARM'); pg.wait_for_timeout(150)
    conn_create('S4HANA_CLOUD', 'billing.rheinau-s4.example', 'S/4HANA Billing', 'RHN_S4U', auth='User Name and Password')
    g.answer('who', 0); g.answer('import', 0)
    g.check('m01 wrong space, wrong answer')
    select_conn('RHN_S4U'); pg.click('#conn-delete'); pg.wait_for_timeout(200)
    pg.select_option('#conn-space', 'RHN_IN'); pg.wait_for_timeout(150)
    conn_create('S4HANA_CLOUD', 'billing.rheinau-s4.example', 'S/4HANA Billing', 'RHN_S4U', auth='User Name and Password')
    validate('RHN_S4U')
    g.check('m01 auth wrong')
    edit_conn('RHN_S4U', auth='OAuth 2.0')
    g.check('m01 not validated after edit')
    validate('RHN_S4U')
    g.answer('who', 1)
    g.shot('c3-connections')
    assert g.check('m01 solved')
    g.next_mission()

    # ---------------- m02: three failures, then fixed
    conn_create('HANA', 'mdm-db.rheinau.local', 'Meter Data (MDM)', 'RHN_MDM', onprem=False)
    validate('RHN_MDM')
    edit_conn('RHN_MDM', onprem=True, location='RHEINAU')
    validate('RHN_MDM')
    edit_conn('RHN_MDM', location='RHEINAU_DC')
    validate('RHN_MDM')
    edit_conn('RHN_MDM', tls=True)
    validate('RHN_MDM')
    g.nav('system'); pg.click('[data-tab="security"]')
    for f in ['Rheinau Web Proxy', 'Rheinau Root CA']:
        pg.click('#cert-upload'); pg.check(f'[name="file"][value="{f}"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    g.shot('c3-system')
    g.nav('connections'); validate('RHN_MDM')
    g.answer('cc', 1)
    g.check('m02 extra certificate')
    g.nav('system'); pg.click('[data-tab="security"]')
    pg.click('[data-cert-delete="Rheinau Web Proxy"]'); pg.wait_for_timeout(200)
    assert g.check('m02 solved')
    g.next_mission()

    # ---------------- m03: remote tables
    g.nav('builder')
    if pg.locator('[data-space="RHN_IN"]').count(): pg.click('[data-space="RHN_IN"]')
    pg.wait_for_selector('#new-tiles')
    # "Show me" for the first task walks through the Import menu (Bild 19)
    tour = lambda t: pg.wait_for_function("t => document.querySelector('.tour-card h2')?.textContent === t", arg=t, timeout=6000)
    pg.click('#task [data-task="0"]'); tour('The Import menu'); pg.click('#import-menu-btn')
    tour('Import Remote Tables'); pg.click('[data-menu-import="remote"]'); pg.wait_for_selector('.dialog [name="conn"]')
    print('   Show me via Import menu: ok'); pg.click('.tour-card [data-act="skip"]'); pg.wait_for_timeout(200)
    pg.select_option('.dialog [name="conn"]', 'RHN_S4U'); pg.wait_for_timeout(150)
    for i in [1, 2, 3]: pg.check(f'[name="obj"][value="{i}"]')   # invoices too (wrong)
    pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(400)
    print('   OBJECTS:', pg.inner_text('#object-list tbody').replace('\n', ' | ')[:300])
    g.answer('big', 0)
    g.check('m03 nothing set yet')
    pg.click('#object-list [data-delete="RHN_IN.RHN_IN_RT_BILLING_INVOICES"]'); pg.wait_for_timeout(300)
    pg.click('#object-list [data-open="RHN_IN.RHN_IN_RT_TARIFFS"]'); pg.wait_for_selector('#column-list')
    pg.click('#run'); pg.wait_for_selector('.result-status')
    print('   PREVIEW:', pg.inner_text('.result-status'))
    g.nav('monitor'); pg.click('[data-mon-tab="queries"]'); pg.wait_for_timeout(200)
    print('   QUERIES:', pg.inner_text('#query-list tbody').replace('\n', ' ')[:200])
    pg.click('[data-mon-tab="remote"]'); pg.wait_for_timeout(200)
    pg.check('[name="rt-sel"][value="RHN_IN_RT_GRID_AREAS"]'); pg.wait_for_timeout(150)
    pg.click('#rt-snapshot'); pg.wait_for_timeout(500)
    pg.check('[name="rt-sel"][value="RHN_IN_RT_GRID_AREAS"]'); pg.wait_for_timeout(150)
    pg.click('#rt-schedule'); pg.check('[name="freq"][value="Weekly"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(150)
    print('   NO CONSENT:', pg.inner_text('.dialog .form-error')); pg.click('[data-act="cancel"]')
    pg.click('#consent-give'); pg.wait_for_timeout(200)
    pg.check('[name="rt-sel"][value="RHN_IN_RT_GRID_AREAS"]'); pg.wait_for_timeout(150)
    pg.click('#rt-schedule'); pg.check('[name="freq"][value="Weekly"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    g.shot('c3-monitor-remote')
    g.answer('big', 1)
    assert g.check('m03 solved')
    g.next_mission()

    # ---------------- m04: replication flow with the truncate trap
    g.nav('builder'); pg.wait_for_selector('#new-tiles')
    pg.click('[data-new="replication"]'); pg.wait_for_selector('#flow-conn')
    pg.select_option('#flow-conn', 'RHN_S4U'); pg.wait_for_timeout(150)
    pg.click('#flow-add'); pg.check('[name="so"][value="0"]'); pg.check('[name="so"][value="1"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    for i in [0, 1]:
        pg.select_option(f'[data-load="{i}"]', 'Initial and Delta')
        pg.check(f'[data-truncate="{i}"]')
    pg.fill('#prop-business', 'S/4HANA billing replication'); pg.fill('#prop-technical', 'RHN_IN_RF_S4U')
    pg.click('#ed-deploy'); pg.wait_for_timeout(600)
    print('   TOAST:', pg.locator('.toast').all_inner_texts())
    pg.click('#flow-run-ed'); pg.wait_for_timeout(600)
    print('   RUN DIALOG:', pg.inner_text('.dialog .guide-lead')[:220]); pg.click('.dialog [type="submit"]')
    g.check('m04 truncate on, not run')
    for i in [0, 1]: pg.uncheck(f'[data-truncate="{i}"]')
    pg.click('#ed-deploy'); pg.wait_for_timeout(500)
    pg.click('#flow-run-ed'); pg.wait_for_timeout(800)
    g.shot('c3-flow-editor')
    g.nav('monitor'); pg.click('[data-mon-tab="flows"]'); pg.click('[data-flow="RHN_IN_RF_S4U"]'); pg.wait_for_selector('#run-log')
    print('   LOG:', pg.inner_text('#run-log').replace('\n', ' | ')[:400])
    g.shot('c3-monitor-flows')
    g.answer('delta', 1)
    assert g.check('m04 solved')
    g.next_mission()

    # ---------------- m05: CRM via S3, projection
    g.nav('connections')
    conn_create('S3', 'rheinau-crm-export', 'CRM Export', 'RHN_CRM')
    validate('RHN_CRM')
    g.nav('builder'); pg.wait_for_selector('#new-tiles')
    pg.click('[data-new="replication"]'); pg.wait_for_selector('#flow-conn')
    pg.select_option('#flow-conn', 'RHN_CRM'); pg.wait_for_timeout(150)
    pg.click('#flow-add'); pg.check('[name="so"][value="0"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    print('   CRM target suggestion:', pg.input_value('[data-target="0"]'))
    pg.click('[data-proj="0"]'); pg.fill('[name="col"]', 'src_sys_id'); pg.fill('[name="val"]', 'crm'); pg.click('#proj-add'); pg.click('.dialog [type="submit"]')
    pg.fill('#prop-business', 'CRM export'); pg.fill('#prop-technical', 'RHN_IN_RF_CRM')
    pg.click('#ed-deploy'); pg.wait_for_timeout(500)
    pg.click('#flow-run-ed'); pg.wait_for_timeout(800)
    g.answer('remote', 1)
    g.check('m05 wrong value, no truncate, no schedule')
    pg.click('[data-proj="0"]'); pg.click('[data-x="0"]'); pg.fill('[name="col"]', 'SRC_SYS_ID'); pg.fill('[name="val"]', 'CRM'); pg.click('#proj-add'); pg.click('.dialog [type="submit"]')
    pg.check('[data-truncate="0"]')
    pg.click('#ed-deploy'); pg.wait_for_timeout(500)
    pg.click('#flow-run-ed'); pg.wait_for_timeout(800)
    g.nav('monitor'); pg.click('[data-mon-tab="flows"]'); pg.click('[data-flow="RHN_IN_RF_CRM"]'); pg.wait_for_selector('#flow-schedule')
    pg.click('#flow-schedule'); pg.check('[name="freq"][value="Daily"]'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    assert g.check('m05 solved')
    g.nav('builder'); pg.wait_for_selector('#object-list')
    pg.click('#object-list [data-open="RHN_IN.CRM_CUSTOMERS"]'); pg.wait_for_selector('#column-list')
    print('   CRM columns:', pg.inner_text('#column-list tbody').replace('\n', ' ')[-60:])
    g.next_mission()

    # ---------------- m06: failed load, locked space
    g.nav('spaces')
    print('   SPACE IN:', pg.inner_text('[data-space-tile="RHN_IN"]').replace('\n', ' | '))
    g.shot('c3-locked')
    pg.click('[data-unlock="RHN_IN"]'); pg.wait_for_timeout(200)
    print('   UNLOCK TOO EARLY:', pg.locator('.toast').all_inner_texts())
    g.nav('monitor'); pg.click('[data-mon-tab="flows"]'); pg.click('[data-flow="RHN_IN_RF_MDM"]'); pg.wait_for_selector('#run-log')
    print('   FAILED LOG:', pg.inner_text('#run-log').replace('\n', ' | ')[:400])
    pg.click('#flow-run'); pg.wait_for_timeout(600)
    g.answer('notice', 0)
    g.check('m06 still locked')
    g.nav('spaces')
    pg.click('[data-edit="RHN_IN"]'); pg.fill('[name="disk"]', '47'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    pg.click('[data-unlock="RHN_IN"]'); pg.wait_for_timeout(200)
    g.check('m06 too little headroom, not rerun')
    pg.click('[data-edit="RHN_IN"]'); pg.fill('[name="disk"]', '48'); pg.click('.dialog [type="submit"]'); pg.wait_for_timeout(200)
    g.nav('monitor'); pg.click('[data-mon-tab="flows"]'); pg.click('[data-flow="RHN_IN_RF_MDM"]'); pg.wait_for_selector('#flow-run')
    pg.click('#flow-run'); pg.wait_for_timeout(600)
    assert g.check('m06 solved')

    # ---------------- persistence
    g.reload()
    g.nav('builder'); pg.click('[data-space="RHN_IN"]'); pg.wait_for_selector('#object-list')
    pg.click('#object-list [data-open="RHN_IN.CRM_CUSTOMERS"]'); pg.wait_for_selector('#column-list')
    print('AFTER RELOAD CRM last column:', pg.locator('#column-list tbody tr').last.inner_text().replace('\n', ' '))
    pg.click('#ed-back'); pg.click('#object-list [data-open="RHN_IN.RHN_IN_RT_GRID_AREAS"]'); pg.wait_for_selector('#column-list')
    pg.click('#run'); pg.wait_for_selector('.result-status')
    print('AFTER RELOAD remote preview:', pg.inner_text('.result-status'))
    print('NEXT MISSION:', pg.inner_text('.mission-head h2'))
    g.done()
